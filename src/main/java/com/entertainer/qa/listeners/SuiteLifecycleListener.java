package com.entertainer.qa.listeners;

import com.entertainer.qa.config.ConfigManager;
import org.testng.ISuite;
import org.testng.ISuiteListener;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Properties;

/**
 * Writes an Allure {@code environment.properties} file at the start of the run, so every report
 * records which environment and base URLs it actually tested against - useful once the suite is
 * run from multiple CI/CD pipelines against different {@code -Denv} values.
 */
public class SuiteLifecycleListener implements ISuiteListener {

    /** Matches the {@code allure.results.directory} system property surefire sets from pom.xml,
     * falling back to the same default when run outside Maven (e.g. directly via an IDE). */
    private static final Path ALLURE_RESULTS_DIR =
            Path.of(System.getProperty("allure.results.directory", "target/allure-results"));

    @Override
    public void onStart(ISuite suite) {
        Properties environment = new Properties();
        environment.setProperty("Environment", ConfigManager.getEnv());
        environment.setProperty("ReqRes.BaseUrl", safe("reqres.base.url"));
        environment.setProperty("Booker.BaseUrl", safe("booker.base.url"));
        environment.setProperty("JsonPlaceholder.BaseUrl", safe("jsonplaceholder.base.url"));

        try {
            Files.createDirectories(ALLURE_RESULTS_DIR);
            try (OutputStream out = Files.newOutputStream(ALLURE_RESULTS_DIR.resolve("environment.properties"))) {
                environment.store(out, "Generated by SuiteLifecycleListener");
            }
        } catch (IOException e) {
            System.err.println("[SuiteLifecycleListener] Could not write Allure environment.properties: " + e.getMessage());
        }

        System.out.println("=== " + suite.getName() + " starting against env=" + ConfigManager.getEnv() + " ===");
    }

    @Override
    public void onFinish(ISuite suite) {
        System.out.println("=== " + suite.getName() + " finished ===");
    }

    private static String safe(String key) {
        String value = ConfigManager.get(key);
        return value != null ? value : "unset";
    }
}
